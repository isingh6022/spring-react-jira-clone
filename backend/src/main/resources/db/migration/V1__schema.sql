create table contributor (
    id        bigint generated by default as identity primary key,
    name      varchar(200) not null,
    expertise varchar(30)  not null
);

create table task (
    id                 bigint generated by default as identity primary key,
    title              varchar(200) not null,
    expertise          varchar(30)  not null,
    priority           varchar(10)  not null default 'MEDIUM',
    state              varchar(20)  not null default 'ROUTING',
    assignee_id        bigint references contributor (id),
    demo_never_routes  boolean      not null default false,
    created_at         timestamptz  not null default now(),
    routing_started_at timestamptz,
    version            bigint       not null default 0
);

-- Append-only history: who did what, and the state it left the task in.
create table task_event (
    id      bigint generated by default as identity primary key,
    task_id bigint        not null references task (id),
    at      timestamptz   not null default now(),
    actor   varchar(200)  not null,
    state   varchar(20),
    message varchar(1000) not null
);
